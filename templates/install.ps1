# Installs {{NAME}}.
#
#   irm https://raw.githubusercontent.com/{{REPO}}/main/install.ps1 | iex
#
# (install.sh does the same on macOS and Linux.)
#
# Downloads the release's {{APP}}.exe, checks it against the release
# manifest, and runs `{{APP}} install`, which copies it to
# %LOCALAPPDATA%\{{APP}}. The bin folder is added to your user PATH. After
# that {{NAME}} updates itself.
{{ABOUT}}#
# Set {{ENV}}_VERSION to a release's version (for example 0.1.0) to install
# that release instead of the latest. The app still updates itself to the
# latest release afterwards unless {{ENV}}_DISABLE_AUTOUPDATER is set.
#
# Generated by Abalone's InstallScript: change it there, not here.

param(
    [string]$Version = $env:{{ENV}}_VERSION,
    # A local {{APP}}.exe to install instead of downloading (for testing).
    [string]$Exe = $env:{{ENV}}_EXE
)

# In a script block, so the settings below don't stay in the session that
# ran `irm | iex`.
& {
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
# GitHub needs TLS 1.2, which Windows PowerShell 5.1 may not offer by default.
$Protocols = [Net.ServicePointManager]::SecurityProtocol
[Net.ServicePointManager]::SecurityProtocol = $Protocols -bor [Net.SecurityProtocolType]::Tls12

$Name = '{{NAME}}'
$App = '{{APP}}'
$Repo = '{{REPO}}'
# Not one the session that ran this already had: the cleanup deletes it.
$Temp = $null

try {
    if (-not [Environment]::Is64BitOperatingSystem) {
        throw "$Name needs 64-bit Windows."
    }
    $Arm = $env:PROCESSOR_ARCHITECTURE -eq 'ARM64' -or $env:PROCESSOR_ARCHITEW6432 -eq 'ARM64'
    $Platform = if ($Arm) { 'windows-arm64' } else { 'windows-x64' }

    $Root = if ($env:{{ENV}}_HOME) { $env:{{ENV}}_HOME } else { Join-Path $env:LOCALAPPDATA $App }
    $Bin = Join-Path $Root 'bin'
    $Temp = Join-Path ([IO.Path]::GetTempPath()) ("$App-install-" + [Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Force -Path $Temp | Out-Null

    Write-Host ''
    Write-Host "Installing $Name"

    $download = Join-Path $Temp "$App.exe"
    if ($Exe) {
        Write-Host "  Using $Exe"
        Copy-Item -LiteralPath $Exe -Destination $download
    } else {
        if ($Version) {
            # Tags have no v prefix; accept one anyway.
            $manifestUrl = "https://github.com/$Repo/releases/download/$($Version.TrimStart('v'))/manifest.json"
        } else {
            $manifestUrl = "https://github.com/$Repo/releases/latest/download/manifest.json"
        }
        $manifest = Invoke-RestMethod -UseBasicParsing -Uri $manifestUrl
        $asset = $manifest.platforms.$Platform
        # Arm Windows runs x64 builds too.
        if (-not $asset -and $Arm) { $asset = $manifest.platforms.'windows-x64' }
        if (-not $asset) { throw "release $($manifest.version) has no $Platform build" }
        if (-not $asset.sha256) { throw "release $($manifest.version) has no SHA-256 for $($asset.file)" }
        Write-Host "  Downloading $Name $($manifest.version)"
        Invoke-WebRequest -UseBasicParsing -Uri "https://github.com/$Repo/releases/download/$($manifest.version)/$($asset.file)" -OutFile $download
        $actual = (Get-FileHash -Algorithm SHA256 -LiteralPath $download).Hash.ToLowerInvariant()
        if ($actual -ne $asset.sha256.ToLowerInvariant()) {
            throw "$($asset.file) has SHA-256 $actual, expected $($asset.sha256)"
        }
    }

    # The user PATH as stored, %VARIABLES% unexpanded, so writing it back
    # keeps them (and its type, REG_EXPAND_SZ).
    $userPath = (Get-Item -LiteralPath 'HKCU:\Environment').GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
    $entries = @($userPath -split ';' | Where-Object { $_ })
    if ($entries -notcontains $Bin) {
        Set-ItemProperty -LiteralPath 'HKCU:\Environment' -Name 'Path' -Value (($entries + $Bin) -join ';') -Type ExpandString
        # Setting a variable through .NET tells open programs (Explorer, so new
        # terminals) that the environment changed; this one is gone again after.
        [Environment]::SetEnvironmentVariable('{{ENV}}_INSTALLING', '1', 'User')
        [Environment]::SetEnvironmentVariable('{{ENV}}_INSTALLING', $null, 'User')
        Write-Host "  Added $Bin to your PATH"
    }
    if (($env:Path -split ';') -notcontains $Bin) { $env:Path = "$env:Path;$Bin" }

    # {{NAME}} copies itself into place.
    & $download install
    if ($LASTEXITCODE -ne 0) { throw "$App install failed" }
{{AFTER}}
    Write-Host ''
    Write-Host '{{DONE}}'
    Write-Host ''
} finally {
    if ($Temp) { Remove-Item -LiteralPath $Temp -Recurse -Force -ErrorAction SilentlyContinue }
    [Net.ServicePointManager]::SecurityProtocol = $Protocols
}
}
